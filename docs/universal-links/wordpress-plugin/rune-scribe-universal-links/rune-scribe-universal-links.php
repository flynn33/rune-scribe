final class Rune_Scribe_Universal_Links {
	const VERSION = '1.0.0';
	const PAGE_SLUG = 'rune-scribe';
	const APP_STORE_URL = 'https://apps.apple.com/us/app/rune-scribe/id6782169761';

	/**
	 * Register the isolated website hooks used by Rune Scribe invitations.
	 */
	public static function bootstrap() {
		add_action( 'init', array( __CLASS__, 'maybe_serve_association' ), 0 );
		add_action( 'wp_enqueue_scripts', array( __CLASS__, 'enqueue_assets' ) );
		add_action( 'wp_head', array( __CLASS__, 'render_smart_app_banner' ), 1 );
		add_filter( 'the_content', array( __CLASS__, 'append_import_help' ), 20 );
	}

	/**
	 * Serve Apple's association document from either supported root path.
	 */
	public static function maybe_serve_association() {
		$request_uri = isset( $_SERVER['REQUEST_URI'] ) ? wp_unslash( $_SERVER['REQUEST_URI'] ) : '';
		$path = wp_parse_url( $request_uri, PHP_URL_PATH );
		$paths = array(
			'/.well-known/apple-app-site-association',
			'/apple-app-site-association',
		);

		if ( ! is_string( $path ) || ! in_array( $path, $paths, true ) ) {
			return;
		}

		$method = isset( $_SERVER['REQUEST_METHOD'] ) ? strtoupper( sanitize_text_field( wp_unslash( $_SERVER['REQUEST_METHOD'] ) ) ) : 'GET';
		if ( ! in_array( $method, array( 'GET', 'HEAD' ), true ) ) {
			status_header( 405 );
			header( 'Allow: GET, HEAD' );
			exit;
		}

		$body = wp_json_encode( self::association_document(), JSON_UNESCAPED_SLASHES );
		if ( ! is_string( $body ) ) {
			status_header( 500 );
			exit;
		}

		status_header( 200 );
		header( 'Content-Type: application/json; charset=utf-8' );
		header( 'Content-Length: ' . strlen( $body ) );
		header( 'Cache-Control: public, max-age=3600' );
		header( 'X-Content-Type-Options: nosniff' );

		if ( 'GET' === $method ) {
			echo $body; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- JSON is generated by wp_json_encode.
		}

		exit;
	}

	/**
	 * Return the exact Rune Scribe Universal Link contract.
	 *
	 * @return array<string, mixed>
	 */
	private static function association_document() {
		return array(
			'applinks' => array(
				'details' => array(
					array(
						'appIDs' => array( '9AQ2C2838M.com.runescribe.app' ),
						'components' => array(
							array(
								'/' => '/rune-scribe/',
								'?' => array( 'runescribe' => 'import' ),
								'comment' => 'Current Rune Scribe cipher invitation links',
							),
							array(
								'/' => '/rune-scribe/import',
								'comment' => 'Compatible cipher invitation links from earlier builds',
							),
							array(
								'/' => '/rune-scribe/import/',
								'comment' => 'Compatible cipher invitation links from earlier builds',
							),
						),
					),
				),
			),
		);
	}

	/**
	 * Load the invitation fallback assets only on the Rune Scribe page.
	 */
	public static function enqueue_assets() {
		if ( ! is_page( self::PAGE_SLUG ) ) {
			return;
		}

		$base_url = plugin_dir_url( __FILE__ ) . 'assets/';
		wp_enqueue_style(
			'rune-scribe-import-help',
			$base_url . 'rune-scribe-import-help.css',
			array(),
			self::VERSION
		);
		wp_enqueue_script(
			'rune-scribe-import-help',
			$base_url . 'rune-scribe-import-help.js',
			array(),
			self::VERSION,
			true
		);
	}

	/**
	 * Advertise the official App Store listing on the Rune Scribe page.
	 */
	public static function render_smart_app_banner() {
		if ( ! is_page( self::PAGE_SLUG ) ) {
			return;
		}

		echo '<meta name="apple-itunes-app" content="app-id=6782169761">' . "\n";
	}

	/**
	 * Append a hidden panel that the local script reveals for exact import links.
	 *
	 * @param string $content Page content.
	 * @return string
	 */
	public static function append_import_help( $content ) {
		if ( ! is_page( self::PAGE_SLUG ) || ! is_main_query() || ! in_the_loop() ) {
			return $content;
		}

		$panel = sprintf(
			'<section id="rune-scribe-import-help" class="rune-scribe-import-help" aria-labelledby="rune-scribe-import-help-title" hidden>' .
			'<div class="rune-scribe-import-help__mark" aria-hidden="true">&#x16B1;</div>' .
			'<div class="rune-scribe-import-help__content">' .
			'<h2 id="rune-scribe-import-help-title">%1$s</h2>' .
			'<p>%2$s</p>' .
			'<p><a class="rune-scribe-import-help__button" href="%3$s">%4$s</a></p>' .
			'<p class="rune-scribe-import-help__note">%5$s</p>' .
			'</div>' .
			'</section>',
			esc_html__( 'Rune Scribe is required to import this cipher', 'rune-scribe-universal-links' ),
			esc_html__( 'Install Rune Scribe from the App Store. After installation, return to the original message and tap the runic tablet again.', 'rune-scribe-universal-links' ),
			esc_url( self::APP_STORE_URL ),
			esc_html__( 'Get Rune Scribe on the App Store', 'rune-scribe-universal-links' ),
			esc_html__( 'The cipher remains in the original invitation. This webpage does not import, decode, or store it.', 'rune-scribe-universal-links' )
		);

		return $panel . $content;
	}
}

Rune_Scribe_Universal_Links::bootstrap();
