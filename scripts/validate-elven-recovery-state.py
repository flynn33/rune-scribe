#!/usr/bin/env python3
"""Fail-closed validation for the neutral Elven recovery state."""

from __future__ import annotations

import argparse
import hashlib
import json
import zipfile
from pathlib import Path
from typing import Any, Iterable


CANONICAL_STAT = "stat.message.incoming-decoded.unique"
FORBIDDEN_STAT_IDS = {"stat.messages-decoded", "stat.messages-decoded.unique"}
EXPECTED_FINDINGS = {f"DEV-ELVEN-{index:03d}" for index in range(1, 10)}
RECOVERY_STATUS = "PASS / CLOSED"
RECOVERY_ACCEPTANCE_OUTCOME = "PASS / UNBLOCKED FOR PHASE C"
PHASE_C_OUTCOME = "PHASE C: PASS / MERGED TO MAIN"
APPLICATION_VERSION = "1.0.38"
APPLICATION_BUILD = "38"
AUDITED_SOURCE_COMMIT = "f5b74658bb6ec4d3ac251f532a4d92d389c2a2db"
EVIDENCE_COMMIT = "ee47191d131dfe3b6b3e446bc4bd88e07bc9960f"
MERGE_COMMIT = "e9e0e0c8814aaa107d7480e070f14a6fe9b09975"


def flatten(value: Any) -> Iterable[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, list):
        for item in value:
            yield from flatten(item)
    elif isinstance(value, dict):
        for key, item in value.items():
            yield str(key)
            yield from flatten(item)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("state", type=Path)
    arguments = parser.parse_args()
    state_path = arguments.state.resolve()
    if len(state_path.parents) < 4:
        print(json.dumps({"status": "FAIL", "errors": ["State path is not inside the expected repository documentation tree."]}, indent=2))
        return 1
    current_repo_root = state_path.parents[3]
    errors: list[str] = []

    try:
        state = json.loads(state_path.read_text(encoding="utf-8"))
    except Exception as error:
        print(json.dumps({"status": "FAIL", "errors": [f"Unable to parse state: {error}"]}, indent=2))
        return 1

    if state.get("applicationVersion") != APPLICATION_VERSION:
        errors.append("recovery state application version differs")
    if state.get("applicationBuild") != APPLICATION_BUILD:
        errors.append("recovery state application build differs")

    repository = state.get("repository", {})
    repo_root = Path(repository.get("root", "missing"))
    if state.get("taskPackageVersion") != "3.0":
        errors.append("taskPackageVersion must be 3.0")
    if not repo_root.is_dir():
        errors.append("repository root is missing")

    strings = list(flatten(state))
    lowered = [item.lower() for item in strings]
    prohibited_attribution = [
        "Chat" + "GPT",
        "Open" + "AI",
        "Anth" + "ropic",
        "Clau" + "de",
        "Gem" + "ini",
        "generated by " + "AI",
        "created by " + "AI",
        "language " + "model",
    ]
    for term in prohibited_attribution:
        if any(term.lower() in item for item in lowered):
            errors.append(f"prohibited attribution remains in recovery state: {term}")
    if any("/runeforge/" in item for item in lowered):
        errors.append("noncanonical document-tree path remains")
    for forbidden in FORBIDDEN_STAT_IDS:
        if forbidden in strings:
            errors.append(f"forbidden statistic ID remains: {forbidden}")
    if CANONICAL_STAT not in strings:
        errors.append(f"canonical statistic ID is missing: {CANONICAL_STAT}")

    prior = state.get("priorAttemptAudit", {})
    if prior.get("complete") is not True:
        errors.append("prior attempt audit is incomplete")
    for key in (
        "repositoryDeltaEvidence",
        "externalTreeDiffEvidence",
        "consistencyAuditEvidence",
        "artifactDispositionEvidence",
    ):
        relative = prior.get(key)
        if not relative or not (repo_root / relative).is_file():
            errors.append(f"priorAttemptAudit.{key} is missing or unresolved")

    phase_ab = state.get("phaseABRegression", {})
    if phase_ab.get("status") != "PASS":
        errors.append("Phase A/B regression must be PASS")
    phase_ab_commands = "\n".join(str(item) for item in phase_ab.get("commands", [])).lower()
    for token in ("swift test", "check-architecture", "check-roadmap", "xcodebuild", "shipping"):
        if token not in phase_ab_commands:
            errors.append(f"Phase A/B commands do not include {token}")
    phase_ab_evidence = phase_ab.get("evidencePath")
    if not phase_ab_evidence or not (repo_root / phase_ab_evidence).is_file():
        errors.append("Phase A/B evidence path is unresolved")
    if "physicalDeviceStatus" in phase_ab or "physicalDevicePending" in phase_ab:
        errors.append("current Phase A/B state retains a hardware gate or residual-work field")
    owner_validation = phase_ab.get("ownerOperatedOptionalValidation", {})
    if owner_validation.get("scope") != "HARDWARE_ONLY":
        errors.append("Phase A/B owner-operated observation scope differs")
    if owner_validation.get("status") != "OUTSIDE_AGENT_SCOPE":
        errors.append("Phase A/B owner-operated observation must be outside Agent Coding scope")
    if owner_validation.get("gatingEffect") != "NONE":
        errors.append("Phase A/B owner-operated observation must have no gating effect")

    findings = state.get("findings", [])
    finding_ids = {item.get("id") for item in findings if isinstance(item, dict)}
    if len(findings) != 9 or finding_ids != EXPECTED_FINDINGS:
        errors.append("exactly the nine controlled findings are required")
    for finding in findings:
        finding_id = finding.get("id", "unknown")
        if finding.get("status") != "PASS":
            errors.append(f"{finding_id} is not PASS")
        if finding.get("priorDisposition") in (None, "UNREVIEWED"):
            errors.append(f"{finding_id} prior disposition is unreviewed")
        for key in ("canonicalSourceFilesChanged", "validators", "commands", "results", "evidencePaths", "stableIDs", "hashes"):
            if not finding.get(key):
                errors.append(f"{finding_id}.{key} is empty")
        for relative in finding.get("evidencePaths", []):
            if not (repo_root / relative).is_file():
                errors.append(f"{finding_id} evidence is unresolved: {relative}")
        if finding.get("unresolvedSubcriteria"):
            errors.append(f"{finding_id} has unresolved subcriteria")
        if finding.get("specificBlockedAsset"):
            errors.append(f"{finding_id} retains a blocked asset")

    package = state.get("correctedV3Package", {})
    package_root = Path(package.get("root", "missing"))
    archive = Path(package.get("archive", "missing"))
    package_manifest = Path(package.get("packageManifest", "missing"))
    if package.get("result") != "PASS":
        errors.append("corrected v3 package result is not PASS")
    if not package_root.is_dir() or not package_manifest.is_file() or not archive.is_file():
        errors.append("corrected v3 package, manifest, or archive is missing")
    else:
        actual_files = [path for path in package_root.rglob("*") if path.is_file()]
        manifest = json.loads(package_manifest.read_text(encoding="utf-8"))
        if len(actual_files) != package.get("fileCount"):
            errors.append("corrected v3 file count differs")
        if len(manifest.get("files", [])) != package.get("manifestEntryCount"):
            errors.append("corrected v3 manifest entry count differs")
        if sum(path.stat().st_size for path in actual_files) != package.get("byteTotal"):
            errors.append("corrected v3 byte total differs")
        if sha256(package_manifest) != package.get("packageManifestSHA256"):
            errors.append("corrected v3 manifest hash differs")
        if archive.stat().st_size != package.get("archiveByteLength"):
            errors.append("corrected v3 archive byte length differs")
        if sha256(archive) != package.get("archiveSHA256"):
            errors.append("corrected v3 archive hash differs")
        try:
            with zipfile.ZipFile(archive) as bundle:
                corrupt_member = bundle.testzip()
                roots = {Path(name).parts[0] for name in bundle.namelist() if Path(name).parts}
            if corrupt_member is not None:
                errors.append(f"archive member failed CRC: {corrupt_member}")
            if roots != {package_root.name}:
                errors.append("archive root differs from corrected package root")
        except Exception as error:
            errors.append(f"archive integrity check failed: {error}")
    if package.get("archiveIntegrity") != "PASS":
        errors.append("archive integrity status is not PASS")

    validation = state.get("fullValidation", {})
    if validation.get("status") != "PASS":
        errors.append("full validation status is not PASS")
    if not validation.get("commands") or not validation.get("results"):
        errors.append("full validation commands or results are missing")
    if validation.get("skippedOrWaivedChecks"):
        errors.append("full validation contains skipped or waived checks")

    continuation = state.get("phaseCContinuation", {})
    if continuation.get("applicationVersion") != APPLICATION_VERSION:
        errors.append("Phase C application version differs")
    if continuation.get("applicationBuild") != APPLICATION_BUILD:
        errors.append("Phase C application build differs")
    if continuation.get("status") != "PASS":
        errors.append("Phase C continuation is not PASS")
    if continuation.get("outcome") != PHASE_C_OUTCOME:
        errors.append("Phase C continuation outcome differs")
    if continuation.get("correctedV31PackageStatus") != "ACCEPTED":
        errors.append("corrected v3.1 package must be ACCEPTED")
    if continuation.get("firstIncompletePhase") != "Phase D - Build the four Theme Modules":
        errors.append("Phase C continuation does not identify Phase D as the next incomplete phase")
    if continuation.get("phaseDReadiness") != "READY_FOR_AUTHORIZATION":
        errors.append("Phase D must be ready for authorization")
    if continuation.get("phaseDStatus") != "NOT_STARTED":
        errors.append("Phase D must remain NOT_STARTED")
    if continuation.get("pullRequestNumber") != 45:
        errors.append("Phase C pull request number differs")
    if continuation.get("pullRequestState") != "MERGED":
        errors.append("Phase C pull request must be MERGED")
    if continuation.get("targetBranch") != "main":
        errors.append("Phase C target branch must be main")
    if continuation.get("mergeCommit") != MERGE_COMMIT:
        errors.append("Phase C merge commit differs")
    if continuation.get("auditedSourceCommit") != AUDITED_SOURCE_COMMIT:
        errors.append("Phase C audited source commit differs")
    if continuation.get("evidenceCommit") != EVIDENCE_COMMIT:
        errors.append("Phase C evidence commit differs")
    if not continuation.get("sourceFilesChanged") or not continuation.get("commands") or not continuation.get("results") or not continuation.get("evidencePaths"):
        errors.append("Phase C continuation lacks source changes, commands, results, or evidence")
    if continuation.get("remainingWork") != []:
        errors.append("Phase C continuation remainingWork must be present and empty")
    if "physicalDeviceStatus" in continuation:
        errors.append("Phase C continuation retains hardware status")
    if "physicalDevicePending" in continuation:
        errors.append("Phase C continuation retains hardware procedures")
    for relative in continuation.get("evidencePaths", []):
        if not (current_repo_root / relative).is_file():
            errors.append(f"Phase C evidence is unresolved: {relative}")

    if state.get("recoveryAcceptanceOutcome") != RECOVERY_ACCEPTANCE_OUTCOME:
        errors.append("recoveryAcceptanceOutcome must preserve the Phase C acceptance result")
    if state.get("recoveryStatus") != RECOVERY_STATUS:
        errors.append("recoveryStatus must be PASS / CLOSED")

    report = {"status": "PASS" if not errors else "FAIL", "errors": errors}
    print(json.dumps(report, indent=2))
    return 0 if not errors else 1


if __name__ == "__main__":
    raise SystemExit(main())
